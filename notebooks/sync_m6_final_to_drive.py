def _has_file_based_root(source):
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return True
    for node in ast.walk(tree):
        if not isinstance(node, ast.Assign):
            continue
        if not any(getattr(t, "id", "") == "PROJECT_ROOT" for t in node.targets):
            continue
        seg = ast.dump(node.value)
        if "__file__" in seg:
            return True
    return False


