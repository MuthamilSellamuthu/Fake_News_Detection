    results[item["name"]] = {"exists": exists, "size": size, "sha256": digest}
    record("%s exists" % item["name"], exists)
    record("%s size == %d" % (item["name"], item["size"]), size == item["size"])
    record("%s sha256 matches" % item["name"], digest == item["sha256"])

