# ---------------------------------------------------------------- write
print("WRITING")
for item in PAYLOAD:
    dest = PROJECT / item["path"]
    dest.parent.mkdir(parents=True, exist_ok=True)
    old = dest.stat().st_size if dest.exists() else 0
    data = base64.b64decode("".join(item["b64"]))
    tmp = dest.with_suffix(dest.suffix + ".tmp")
    tmp.write_bytes(data)
    tmp.replace(dest)                      # atomic replace
    print("  %-42s %d -> %d bytes" % (item["path"], old, dest.stat().st_size))

# stale bytecode would let Python import the OLD module even after the
